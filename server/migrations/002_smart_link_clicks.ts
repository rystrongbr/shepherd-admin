/**
 * Migration 002 — smart_link_clicks (Postgres parity for the SQLite table
 * created lazily by server/smart-link/store.ts).
 *
 * Usage (Railway one-off or local):
 *   DATABASE_URL=... npx tsx server/migrations/002_smart_link_clicks.ts
 *
 * PII-free by design: timestamp, whitelisted src/campaign labels and a coarse
 * platform bucket only. No IP, no User-Agent.
 *
 * Idempotent: IF NOT EXISTS throughout. Safe to run repeatedly.
 */

import PgPool from "pg-pool";

const DATABASE_URL = process.env.DATABASE_URL;

const statements = [
  `CREATE TABLE IF NOT EXISTS smart_link_clicks (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at text NOT NULL,
    src text NOT NULL DEFAULT 'unknown',
    campaign text NOT NULL DEFAULT '',
    platform text NOT NULL DEFAULT 'other'
  )`,
  `CREATE INDEX IF NOT EXISTS idx_smart_link_clicks_created_at ON smart_link_clicks(created_at)`,
];

async function main() {
  if (!DATABASE_URL) throw new Error("DATABASE_URL is required");
  const pool = new PgPool({ connectionString: DATABASE_URL, max: 5 });
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    for (const stmt of statements) {
      console.log("[smart-link-migration] running:", stmt.replace(/\s+/g, " ").slice(0, 80));
      await client.query(stmt);
    }
    await client.query("COMMIT");
    console.log("[smart-link-migration] complete");
  } catch (err) {
    await client.query("ROLLBACK");
    throw err;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch(err => {
  console.error("[smart-link-migration] failed:", err);
  process.exit(1);
});
